BEGIN;

CREATE SCHEMA IF NOT EXISTS linkslice;

CREATE TABLE linkslice.link_list (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias varchar(64) NOT NULL UNIQUE,
    management_key_hash varchar(255) NOT NULL,
    CONSTRAINT link_list_alias_normalized CHECK (alias = lower(btrim(alias)) AND alias <> '')
);

CREATE TABLE linkslice.url (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_original text NOT NULL,
    short_url varchar(255) NOT NULL UNIQUE,
    local_date_time timestamp(6) without time zone NOT NULL,
    list_id bigint REFERENCES linkslice.link_list (id),
    click_count bigint NOT NULL DEFAULT 0 CHECK (click_count >= 0),
    management_key_hash varchar(255),
    CONSTRAINT url_management_key_scope CHECK (list_id IS NULL OR management_key_hash IS NULL)
);

CREATE INDEX url_list_id_idx ON linkslice.url (list_id);

COMMIT;
